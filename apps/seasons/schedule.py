def day_start(year: int, month: int, day: int) -> dt.datetime:
    """Полночь указанного дня по Москве."""
    return dt.datetime(year, month, day, 0, 0, 0, tzinfo=MSK)


def day_end(year: int, month: int, day: int) -> dt.datetime:
    """23:59:59 указанного дня по Москве — последняя секунда суток."""
    return dt.datetime(year, month, day, 23, 59, 59, tzinfo=MSK)


