"""Очистка HTML, который пишут люди: условия задач, тексты страниц.

Условие задачи заводит организатор, и оно выводится как HTML. Без
очистки <script> или onerror= в условии выполнились бы у каждого, кто
открыл задачу, — в том числе у администратора, одобряющего черновик,
с его правами. Поэтому оставляем разметку (абзацы, списки, таблицы,
ссылки, картинки), а скрипты, обработчики событий и javascript:-ссылки
вырезаем.

Формулы не страдают: KaTeX разбирает текст $…$, а не теги.
"""

import nh3


def clean_html(value: str) -> str:
    if not value:
        return ""
    return nh3.clean(value, url_schemes={"http", "https", "mailto", "tel"})
