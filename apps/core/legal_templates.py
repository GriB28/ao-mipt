def _participant_intro(minor: bool, what: str) -> str:
    consent_of = " с согласия моего законного представителя" if minor else ""
    return (f"<p>Я, участник олимпиады, сведения о котором указаны выше, в соответствии "
            f"с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных» свободно, "
            f"своей волей и в своём интересе{consent_of} даю согласие {{{{ operator }}}} "
            f"(далее – оператор) {what}</p>")


def _representative(document: str) -> str:
    """Замечание 3.11: согласие представителя — самостоятельное, прямо,
    без «также» и без «(родитель)»; ссылки — п. 1 ст. 64 СК РФ и ст. 26 ГК РФ."""
    return (f"<p>Я, законный представитель участника, сведения о котором указаны выше, "
            f"действуя в его интересах на основании п. 1 ст. 64 Семейного кодекса РФ "
            f"и ст. 26 Гражданского кодекса РФ, даю согласие на {document} участника "
            f"на изложенных в настоящем согласии условиях.</p>")


def processing(minor: bool) -> str:
    """Документ 1 — согласие на обработку."""
    representative = ""
    if minor:
        # Замечание 3.9: согласие представителя на его собственные данные —
        # те, что он вписывает в бланк от руки.
        representative = _representative("обработку персональных данных") + """
<p>Я, законный представитель участника, даю согласие оператору на обработку моих
персональных данных — фамилии, имени, отчества, данных документа, удостоверяющего
личность, адреса регистрации, сведений о документе, подтверждающем полномочия, — в целях
оформления согласий участника на обработку и на распространение его персональных данных,
на тех же условиях и в тот же срок.</p>
"""
    return f"""
{_participant_intro(minor, "на обработку моих персональных данных на следующих условиях.")}
{representative}
<p><b>Цель обработки:</b> {_PURPOSE}.</p>

<p><b>Перечень персональных данных:</b></p>
{_DATA_LIST}
<p><b>Действия с персональными данными:</b> {_ACTIONS}. Фамилия, имя, отчество и класс
могут предоставляться организации, на базе которой работает выбранная участником площадка
очного тура, — для допуска к туру и его проведения. Обработка персональных данных третьим
лицам по поручению оператора не передаётся.</p>

<p>Оператор обеспечивает конфиденциальность персональных данных; документы с ними хранятся
в архиве оператора в сроки, установленные законодательством РФ. Я имею право на доступ
к моим персональным данным, на их уточнение, блокирование или уничтожение.</p>

<p><b>Согласие действует</b> {TERM} и может быть отозвано полностью или частично
письменным заявлением, направленным оператору {_REVOKE_TO}.</p>
""".strip()


def distribution(minor: bool) -> str:
    """Документ 2 — согласие на распространение (ст. 10.1 152-ФЗ, приказ
    Роскомнадзора № 18). Пустые строки для условий и запретов — в раскладке."""
    representative = ""
    if minor:
        representative = _representative(
            "обработку персональных данных, разрешённых для распространения,") + """
<p>Я осознаю, что указанные персональные данные моего несовершеннолетнего ребёнка
(подопечного) будут общедоступны в сети «Интернет», и принимаю на себя ответственность
за последствия такого распространения.</p>
"""
    return f"""
{_participant_intro(minor, "на обработку моих персональных данных, разрешённых мной для "
                           "распространения, на следующих условиях.")}
{representative}
<p><b>Цель:</b> опубликование результатов олимпиады школьников «Аэрокосмическая олимпиада
МФТИ» (таблицы результатов, списки победителей и призёров) и освещение олимпиады.</p>

<p><b>Информационный ресурс,</b> на котором персональные данные будут доступны
неограниченному кругу лиц: сайт олимпиады {SITE}.</p>

<p><b>Перечень персональных данных, разрешённых для распространения:</b></p>
{_PUBLISHED}
<p>Согласие на распространение изображения является также согласием на его обнародование
и использование в соответствии со ст. 152.1 Гражданского кодекса РФ. Остальные
персональные данные не распространяются.</p>

<p><b>Согласие действует</b> {TERM}. Действие согласия прекращается с момента поступления
оператору требования о прекращении распространения персональных данных, содержащего
фамилию, имя, отчество, контактную информацию и перечень персональных данных,
распространение которых подлежит прекращению. Требование направляется {_REVOKE_TO}.</p>
""".strip()


